export function useBillingCopy() {
  const i18n = useI18n() as unknown as { locale?: unknown }
  const dict = computed<Dict>(() => {
    let code = ''
    try {
      const raw = i18n?.locale
      code = typeof raw === 'string' ? raw : String((raw as { value?: unknown } | null)?.value ?? '')
    } catch {
      code = ''
    }
    return code.toLowerCase().startsWith('en') ? en : zh
  })
  const c = (key: string) => dict.value[key] ?? zh[key] ?? key
  const cf = (key: string, vars: Record<string, string | number>) => {
    const template = dict.value[key] ?? zh[key] ?? key
    return template.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? ''))
  }
  return { c, cf }
}
